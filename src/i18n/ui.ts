const dicts: Record<LangCode, Dict> = {
  "zh-CN": cn,
  "zh-TW": tw,
  "en-US": en,
  "ja-JP": ja,
  "ko-KR": ko,
};

export function getUiText(
  lang: LangCode,
  key: string,
  params?: Record<string, string | number>,
): string {
  const localized = dicts[lang] as Readonly<Record<string, string>>,
    fallback = tw as Readonly<Record<string, string>>;
  let text = localized[key] ?? fallback[key] ?? key;
  if (params)
    for (const [name, value] of Object.entries(params))
      text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
